'use strict';
const assert=require('node:assert/strict'),c=require('../analyzer.js');
const vault=c.challenges[0],b=c.parseHex(vault.bytes),ins=c.decode(b,0,60);
assert.equal(b.length,24);
assert.ok(ins.some(x=>x.mnemonic==='cmp'&&x.operands.includes('0x2a')));
assert.ok(ins.some(x=>x.mnemonic==='jne'&&x.target===20));
assert.equal(c.validate(vault,'42',b),true);
assert.equal(c.validate(vault,'0x2a',b),true);
assert.equal(c.validate(vault,'50',b),false);
const sig=c.challenges[1],s=c.decode(c.parseHex(sig.bytes),0,60);
assert.ok(s.some(x=>x.mnemonic==='cmp'&&x.operands.includes('0x00001337')));
assert.equal(c.validate(sig,'4919',c.parseHex(sig.bytes)),true);
const patch=c.challenges[2],p=c.parseHex(patch.bytes);
assert.equal(c.validate(patch,'',p),false);p[3]=0x74;assert.equal(c.validate(patch,'',p),true);
const st=c.challenges[3],stbytes=c.parseHex(st.bytes);
assert.ok(c.strings(stbytes).some(s=>s.text.includes('MAINT_KEY=ORBIT')));
assert.equal(c.validate(st,'orbit',stbytes),true);
assert.equal(c.info(new Uint8Array([77,90,...Array(126).fill(0)])).format,'PE');
assert.equal(c.info(new Uint8Array([127,69,76,70,2,1,...Array(58).fill(0)])).format,'ELF');
const big=new Uint8Array([0x90,0xc3]);assert.equal(c.hexdump(big)[0].ascii,'..');
assert.ok(c.pseudo(ins).includes('not Ghidra'));
console.log('Passed: browser decode, headers, strings, missions, patch, pseudocode');
